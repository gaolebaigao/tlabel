"""
Ablation Study Script for TacQuad Benchmark

This script performs feature ablation experiments to understand the importance
of each TLabel feature for downstream tasks:
- Force Prediction (Ridge regression)
- Grasp Phase Recognition (Logistic Regression)
- Slip Detection (Random Forest permutation importance)

Data is generated by TLabel (pip install tlabel) and stored as JSON files.

Usage:
    python eval_ablation.py --data-dir ./tlabel_output \
           --output results/ablation_results.json
"""

import argparse
import json
from pathlib import Path
from typing import Dict, List, Tuple

import numpy as np
from sklearn.ensemble import RandomForestClassifier, RandomForestRegressor
from sklearn.inspection import permutation_importance
from sklearn.linear_model import LogisticRegression, Ridge
from sklearn.metrics import f1_score, r2_score
from sklearn.model_selection import KFold
from sklearn.preprocessing import LabelEncoder, StandardScaler

# TLabel feature keys (17 dimensions)
TLABEL_FEATURES = [
    'contact',
    'deformation_magnitude',
    'temporal_deformation_rate',
    'centroid_x',
    'centroid_y',
    'edge_density',
    'texture_energy',
    'optical_flow_magnitude',
    'slip_entropy',
    'friction_cone_ratio',
    'force_direction_x',
    'force_direction_y',
    'force_direction_z',
    'shear_ratio',
    'normal_force',
    'texture_contrast',
    'temporal_stability'
]

# Feature groups for group ablation
FEATURE_GROUPS = {
    'contact': ['contact'],
    'deformation': ['deformation_magnitude', 'temporal_deformation_rate'],
    'force': ['force_direction_x', 'force_direction_y', 'force_direction_z', 'normal_force', 'shear_ratio'],
    'slip': ['slip_entropy', 'friction_cone_ratio'],
    'texture': ['texture_energy', 'texture_contrast'],
    'optical_flow': ['optical_flow_magnitude', 'temporal_stability'],
    'normal_field': ['centroid_x', 'centroid_y', 'edge_density'],
    'shear': ['shear_ratio']
}


def load_all_episodes(data_dir: Path) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    Load all episodes from data directory.
    
    Returns:
        X: Feature matrix (n_samples, 17)
        y_force: Force labels
        y_phase: Phase labels
    """
    all_features = []
    all_force = []
    all_phase = []
    
    scenes = ['fine', 'indoor', 'outdoor']
    
    for scene in scenes:
        scene_path = data_dir / scene
        if not scene_path.exists():
            continue
            
        for object_dir in scene_path.iterdir():
            if not object_dir.is_dir():
                continue
                
            for sensor_file in object_dir.glob('*.json'):
                try:
                    with open(sensor_file, 'r', encoding='utf-8') as f:
                        data = json.load(f)
                    
                    annotations = data.get('annotations', [])
                    ground_truth = data.get('ground_truth', {})
                    
                    for frame in annotations:
                        features = [frame.get(key, 0.0) for key in TLABEL_FEATURES]
                        all_features.append(features)
                        all_force.append(ground_truth.get('force_magnitude', 0.0))
                        
                        # For phase, exclude 'transition' class (only 5 samples)
                        phase = frame.get('phase', 'no_contact')
                        if phase == 'transition':
                            phase = 'no_contact'
                        all_phase.append(phase)
                        
                except (json.JSONDecodeError, KeyError):
                    continue
    
    return np.array(all_features), np.array(all_force), np.array(all_phase)


def leave_one_out_ablation(X: np.ndarray, y: np.ndarray, task: str, n_folds: int = 5) -> List[Dict]:
    """
    Leave-one-feature-out ablation.
    
    Returns list of features sorted by importance (drop in performance when removed).
    """
    kf = KFold(n_splits=n_folds, shuffle=True, random_state=42)
    
    # Compute baseline
    if task == 'force':
        baseline_scores = []
        for train_idx, test_idx in kf.split(X):
            X_train, X_test = X[train_idx], X[test_idx]
            y_train, y_test = y[train_idx], y[test_idx]
            
            scaler = StandardScaler()
            X_train_scaled = scaler.fit_transform(X_train)
            X_test_scaled = scaler.transform(X_test)
            
            model = Ridge(alpha=1.0)
            model.fit(X_train_scaled, y_train)
            baseline_scores.append(r2_score(y_test, model.predict(X_test_scaled)))
        
        baseline = np.mean(baseline_scores)
        
        # Ablation per feature
        results = []
        for i, feature_name in enumerate(TLABEL_FEATURES):
            mask = np.ones(X.shape[1], dtype=bool)
            mask[i] = False
            X_ablate = X[:, mask]
            
            ablate_scores = []
            for train_idx, test_idx in kf.split(X_ablate):
                X_train, X_test = X_ablate[train_idx], X_ablate[test_idx]
                y_train, y_test = y[train_idx], y[test_idx]
                
                scaler = StandardScaler()
                X_train_scaled = scaler.fit_transform(X_train)
                X_test_scaled = scaler.transform(X_test)
                
                model = Ridge(alpha=1.0)
                model.fit(X_train_scaled, y_train)
                ablate_scores.append(r2_score(y_test, model.predict(X_test_scaled)))
            
            drop = baseline - np.mean(ablate_scores)
            results.append({'feature': feature_name, 'drop': float(drop)})
    
    else:  # phase
        le = LabelEncoder()
        y_encoded = le.fit_transform(y)
        
        baseline_scores = []
        for train_idx, test_idx in kf.split(X):
            X_train, X_test = X[train_idx], X[test_idx]
            y_train, y_test = y_encoded[train_idx], y_encoded[test_idx]
            
            scaler = StandardScaler()
            X_train_scaled = scaler.fit_transform(X_train)
            X_test_scaled = scaler.transform(X_test)
            
            model = LogisticRegression(random_state=42, max_iter=1000)
            model.fit(X_train_scaled, y_train)
            baseline_scores.append(f1_score(y_test, model.predict(X_test_scaled), average='macro'))
        
        baseline = np.mean(baseline_scores)
        
        results = []
        for i, feature_name in enumerate(TLABEL_FEATURES):
            mask = np.ones(X.shape[1], dtype=bool)
            mask[i] = False
            X_ablate = X[:, mask]
            
            ablate_scores = []
            for train_idx, test_idx in kf.split(X_ablate):
                X_train, X_test = X_ablate[train_idx], X_ablate[test_idx]
                y_train, y_test = y_encoded[train_idx], y_encoded[test_idx]
                
                scaler = StandardScaler()
                X_train_scaled = scaler.fit_transform(X_train)
                X_test_scaled = scaler.transform(X_test)
                
                model = LogisticRegression(random_state=42, max_iter=1000)
                model.fit(X_train_scaled, y_train)
                ablate_scores.append(f1_score(y_test, model.predict(X_test_scaled), average='macro'))
            
            drop = baseline - np.mean(ablate_scores)
            results.append({'feature': feature_name, 'drop': float(drop)})
    
    # Sort by drop (higher drop = more important)
    results.sort(key=lambda x: x['drop'], reverse=True)
    return results


