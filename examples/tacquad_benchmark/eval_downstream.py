"""
Downstream Evaluation Script for TacQuad Benchmark

This script evaluates TLabel Format features on 4 downstream tasks:
- Contact Detection (binary classification)
- Slip Detection (binary classification)
- Force Prediction (regression)
- Grasp Phase Recognition (7-class classification)

Data is generated by TLabel (pip install tlabel) and stored as JSON files.

Usage:
    python eval_downstream.py --data-dir ./tlabel_output --output results/downstream_results.json
"""

import argparse
import json
import os
from pathlib import Path
from typing import Dict, List, Tuple

import numpy as np
from sklearn.ensemble import RandomForestClassifier, RandomForestRegressor
from sklearn.linear_model import LogisticRegression, Ridge
from sklearn.metrics import accuracy_score, f1_score, mean_squared_error, r2_score
from sklearn.model_selection import KFold
from sklearn.preprocessing import LabelEncoder, StandardScaler

# TLabel feature keys (17 dimensions)
# If tlabel package is available, use tlabel.FEATURE_KEYS instead
TLABEL_FEATURES = [
    'contact',
    'deformation_magnitude',
    'temporal_deformation_rate',
    'centroid_x',
    'centroid_y',
    'edge_density',
    'texture_energy',
    'optical_flow_magnitude',
    'slip_entropy',
    'friction_cone_ratio',
    'force_direction_x',
    'force_direction_y',
    'force_direction_z',
    'shear_ratio',
    'normal_force',
    'texture_contrast',
    'temporal_stability'
]

# Mapping from feature names to indices (for exclusion)
EXCLUDED_FOR_FORCE = {'force_magnitude', 'force_peak'}


def load_all_episodes(data_dir: Path) -> Tuple[np.ndarray, Dict[str, np.ndarray]]:
    """
    Load all episodes from data directory.
    
    Args:
        data_dir: Root directory containing scene/object/sensor.json structure
        
    Returns:
        X: Feature matrix (n_samples, 17)
        y: Dictionary of labels for each task
    """
    all_features = []
    all_contact = []
    all_slip = []
    all_force = []
    all_phase = []
    
    scenes = ['fine', 'indoor', 'outdoor']
    
    for scene in scenes:
        scene_path = data_dir / scene
        if not scene_path.exists():
            continue
            
        for object_dir in scene_path.iterdir():
            if not object_dir.is_dir():
                continue
                
            for sensor_file in object_dir.glob('*.json'):
                try:
                    with open(sensor_file, 'r', encoding='utf-8') as f:
                        data = json.load(f)
                    
                    annotations = data.get('annotations', [])
                    ground_truth = data.get('ground_truth', {})
                    
                    for frame in annotations:
                        # Extract 17 features
                        features = [frame.get(key, 0.0) for key in TLABEL_FEATURES]
                        all_features.append(features)
                        
                        # Extract labels
                        all_contact.append(frame.get('contact', 0))
                        all_slip.append(frame.get('slip', 'no_slip'))
                        all_force.append(ground_truth.get('force_magnitude', 0.0))
                        all_phase.append(frame.get('phase', 'no_contact'))
                        
                except (json.JSONDecodeError, KeyError) as e:
                    print(f"Warning: Skipping {sensor_file}: {e}")
                    continue
    
    X = np.array(all_features)
    
    y = {
        'contact': np.array(all_contact),
        'slip': np.array(all_slip),
        'force': np.array(all_force),
        'phase': np.array(all_phase)
    }
    
    return X, y


def eval_contact_classification(X: np.ndarray, y: np.ndarray) -> Dict:
    """Evaluate contact detection with LR and RF."""
    results = {}
    
    kf = KFold(n_splits=5, shuffle=True, random_state=42)
    
    for name, model_cls in [('lr', LogisticRegression), ('rf', RandomForestClassifier)]:
        acc_list, f1_list = [], []
        
        for train_idx, test_idx in kf.split(X):
            X_train, X_test = X[train_idx], X[test_idx]
            y_train, y_test = y[train_idx], y[test_idx]
            
            model = model_cls(random_state=42, max_iter=1000)
            model.fit(X_train, y_train)
            y_pred = model.predict(X_test)
            
            acc_list.append(accuracy_score(y_test, y_pred))
            f1_list.append(f1_score(y_test, y_pred, average='binary', pos_label=1))
        
        results[f'{name}_acc'] = np.mean(acc_list)
        results[f'{name}_f1'] = np.mean(f1_list)
    
    return results


def eval_slip_classification(X: np.ndarray, y: np.ndarray) -> Dict:
    """Evaluate slip detection with LR and RF."""
    results = {}
    
    le = LabelEncoder()
    y_encoded = le.fit_transform(y)
    
    kf = KFold(n_splits=5, shuffle=True, random_state=42)
    
    for name, model_cls in [('lr', LogisticRegression), ('rf', RandomForestClassifier)]:
        acc_list, f1_list = [], []
        
        for train_idx, test_idx in kf.split(X):
            X_train, X_test = X[train_idx], X[test_idx]
            y_train, y_test = y_encoded[train_idx], y_encoded[test_idx]
            
            model = model_cls(random_state=42, max_iter=1000)
            model.fit(X_train, y_train)
            y_pred = model.predict(X_test)
            
            acc_list.append(accuracy_score(y_test, y_pred))
            f1_list.append(f1_score(y_test, y_pred, average='binary', pos_label=1))
        
        results[f'{name}_acc'] = np.mean(acc_list)
        results[f'{name}_f1'] = np.mean(f1_list)
    
    return results


def eval_force_regression(X: np.ndarray, y: np.ndarray) -> Dict:
    """Evaluate force prediction with Ridge and RF."""
    results = {}
    
    kf = KFold(n_splits=5, shuffle=True, random_state=42)
    
    # Ridge Regression
    ridge_r2_list, ridge_rmse_list = [], []
    for train_idx, test_idx in kf.split(X):
        X_train, X_test = X[train_idx], X[test_idx]
        y_train, y_test = y[train_idx], y[test_idx]
        
        scaler = StandardScaler()
        X_train_scaled = scaler.fit_transform(X_train)
        X_test_scaled = scaler.transform(X_test)
        
        model = Ridge(alpha=1.0)
        model.fit(X_train_scaled, y_train)
        y_pred = model.predict(X_test_scaled)
        
        ridge_r2_list.append(r2_score(y_test, y_pred))
        ridge_rmse_list.append(np.sqrt(mean_squared_error(y_test, y_pred)))
    
    results['ridge_r2'] = np.mean(ridge_r2_list)
    results['ridge_rmse'] = np.mean(ridge_rmse_list)
    
    # Random Forest
    rf_r2_list, rf_rmse_list = [], []
    for train_idx, test_idx in kf.split(X):
        X_train, X_test = X[train_idx], X[test_idx]
        y_train, y_test = y[train_idx], y[test_idx]
        
        model = RandomForestRegressor(n_estimators=100, random_state=42, n_jobs=-1)
        model.fit(X_train, y_train)
        y_pred = model.predict(X_test)
        
        rf_r2_list.append(r2_score(y_test, y_pred))
        rf_rmse_list.append(np.sqrt(mean_squared_error(y_test, y_pred)))
    
    results['rf_r2'] = np.mean(rf_r2_list)
    results['rf_rmse'] = np.mean(rf_rmse_list)
    
    return results


def eval_phase_classification(X: np.ndarray, y: np.ndarray) -> Dict:
    """Evaluate grasp phase recognition with LR and RF."""
    results = {}
    
    le = LabelEncoder()
    y_encoded = le.fit_transform(y)
    
    kf = KFold(n_splits=5, shuffle=True, random_state=42)
    
    for name, model_cls in [('lr', LogisticRegression), ('rf', RandomForestClassifier)]:
        acc_list, f1_list = [], []
        
        for train_idx, test_idx in kf.split(X):
            X_train, X_test = X[train_idx], X[test_idx]
            y_train, y_test = y_encoded[train_idx], y_encoded[test_idx]
            
            if name == 'lr':
                scaler = StandardScaler()
                X_train = scaler.fit_transform(X_train)
                X_test = scaler.transform(X_test)
            
            model = model_cls(random_state=42, max_iter=1000)
            model.fit(X_train, y_train)
            y_pred = model.predict(X_test)
            
            acc_list.append(accuracy_score(y_test, y_pred))
            f1_list.append(f1_score(y_test, y_pred, average='macro'))
        
        results[f'{name}_acc'] = np.mean(acc_list)
        results[f'{name}_f1'] = np.mean(f1_list)
    
    return results


def compute_label_distribution(y: Dict) -> Dict:
    """Compute label distribution for each task."""
    dist = {}
    
    # Contact
    contact_vals, contact_counts = np.unique(y['contact'], return_counts=True)
    dist['contact'] = {str(int(v)): int(c) for v, c in zip(contact_vals, contact_counts)}
    
    # Slip
    slip_vals, slip_counts = np.unique(y['slip'], return_counts=True)
    dist['slip'] = {str(v): int(c) for v, c in zip(slip_vals, slip_counts)}
    
    # Phase
    phase_vals, phase_counts = np.unique(y['phase'], return_counts=True)
    dist['phase'] = {str(v): int(c) for v, c in zip(phase_vals, phase_counts)}
    
    return dist


def compute_sensor_distribution(data_dir: Path) -> Dict:
    """Compute sample distribution across sensors."""
    dist = {}
    
    scenes = ['fine', 'indoor', 'outdoor']
    
    for scene in scenes:
        scene_path = data_dir / scene
        if not scene_path.exists():
            continue
            
        for object_dir in scene_path.iterdir():
            if not object_dir.is_dir():
                continue
                
            for sensor_file in object_dir.glob('*.json'):
                sensor_name = sensor_file.stem
                try:
                    with open(sensor_file, 'r', encoding='utf-8') as f:
                        data = json.load(f)
                    count = len(data.get('annotations', []))
                    dist[sensor_name] = dist.get(sensor_name, 0) + count
                except:
                    continue
    
    return dist


def main():
    parser = argparse.ArgumentParser(description='TacQuad Downstream Evaluation')
    parser.add_argument('--data-dir', type=str, default='./tlabel_output',
                        help='Directory containing TLabel output JSON files')
    parser.add_argument('--output', type=str, default='results/downstream_results.json',
                        help='Output JSON file path')
    args = parser.parse_args()
    
    data_dir = Path(args.data_dir)
    output_path = Path(args.output)
    
    print("Loading data...")
    X, y = load_all_episodes(data_dir)
    print(f"Loaded {X.shape[0]} samples with {X.shape[1]} features")
    
    print("\nEvaluating contact classification...")
    contact_results = eval_contact_classification(X, y['contact'])
    
    print("Evaluating slip classification...")
    slip_results = eval_slip_classification(X, y['slip'])
    
    print("Evaluating force regression...")
    force_results = eval_force_regression(X, y['force'])
    
    print("Evaluating phase classification...")
    phase_results = eval_phase_classification(X, y['phase'])
    
    # Compute distributions
    label_dist = compute_label_distribution(y)
    sensor_dist = compute_sensor_distribution(data_dir)
    
    # Compile results
    results = {
        'dataset': 'TacQuad',
        'samples': int(X.shape[0]),
        'features': int(X.shape[1]),
        'sensors': ['gelsight', 'digit', 'duragel', 'tac3d'],
        'scenes': ['fine', 'indoor', 'outdoor'],
        'episodes': 671,
        'downstream_5fold_cv': {
            'contact': contact_results,
            'slip': slip_results,
            'force': force_results,
            'phase': phase_results
        },
        'label_distribution': label_dist,
        'sensor_distribution': sensor_dist
    }
    
    # Save results
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(results, f, indent=2)
    
    print(f"\nResults saved to {output_path}")
    
    # Print summary
    print("\n" + "="*50)
    print("SUMMARY")
    print("="*50)
    print(f"Contact: LR Acc={contact_results['lr_acc']:.4f}, RF Acc={contact_results['rf_acc']:.4f}")
    print(f"Slip:    LR Acc={slip_results['lr_acc']:.4f}, RF Acc={slip_results['rf_acc']:.4f}")
    print(f"Force:   Ridge R²={force_results['ridge_r2']:.4f}, RF R²={force_results['rf_r2']:.4f}")
    print(f"Phase:   LR Acc={phase_results['lr_acc']:.4f}, RF Acc={phase_results['rf_acc']:.4f}")


if __name__ == '__main__':
    main()
